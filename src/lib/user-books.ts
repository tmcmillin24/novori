export async function getLockedVerifiedCoverUrls(googleBookIds: string[]) {
  const ids = [...new Set(googleBookIds.filter(Boolean))];
  const covers = new Map<string, string>();
  await Promise.all(ids.map(async googleBookId => {
    const url = await resolveCanonicalBookCover({ googleBookId });
    if (url) covers.set(googleBookId, url);
  }));
  return covers;
}

async function getCurrentUserId() {
  const {
    data: { user },
    error,
  } = await supabase.auth.getUser();

  if (error) {
    throw error;
  }

  if (!user) {
    throw new Error('You must be signed in to manage your library.');
  }

  return user.id;
}

export async function getUserBook(
  googleBookId: string
): Promise<UserBook | null> {
  const userId =
    await getCurrentUserId();

  const {
    data,
    error,
  } = await supabase
    .from('user_books')
    .select('*')
    .eq('user_id', userId)
    .eq(
      'google_book_id',
      googleBookId
    )
    .maybeSingle();

  if (error) {
    throw error;
  }

  const book =
    data as UserBook | null;

  if (
    !book
  ) {
    return null;
  }

  const verifiedCovers =
    await getLockedVerifiedCoverUrls([
      book.google_book_id,
    ]);

  const verifiedCover =
    verifiedCovers.get(
      book.google_book_id
    );

  if (
    verifiedCover
  ) {
    return {
      ...book,
      cover_url:
        verifiedCover,
    };
  }

  return book;
}

export async function getUserBooks(
  status?: UserBookStatus
): Promise<UserBook[]> {
  const userId =
    await getCurrentUserId();

  let query =
    supabase
      .from('user_books')
      .select('*')
      .eq('user_id', userId)
      .order(
        'updated_at',
        {
          ascending: false,
        }
      );

  if (status) {
    query =
      query.eq(
        'status',
        status
      );
  }

  const {
    data,
    error,
  } = await query;

  if (error) {
    throw error;
  }

  // List reads must stay fast. Do one server-side batch lookup for
  // locked/verified work covers, but never run per-book remote cover repair.
  const books =
    (
      data ??
      []
    ) as UserBook[];

  const verifiedCovers =
    await getLockedVerifiedCoverUrls(
      books.map(
        (
          book
        ) =>
          book.google_book_id
      )
    );

  if (
    verifiedCovers.size ===
    0
  ) {
    return books;
  }

  return books.map(
    (
      book
    ) => {
      const verifiedCover =
        verifiedCovers.get(
          book.google_book_id
        );

      return verifiedCover
        ? {
            ...book,
            cover_url:
              verifiedCover,
          }
        : book;
    }
  );
}

export async function saveUserBook(
  input: SaveUserBookInput
): Promise<UserBook> {
  const userId =
    await getCurrentUserId();

  const canonicalCover = await resolveCanonicalBookCover({
    googleBookId: input.googleBookId,
    isbn: input.isbn,
    existingCoverUrl: input.coverUrl,
  });
  input = { ...input, coverUrl: canonicalCover };

  const now =
    new Date().toISOString();

  const existing =
    await getUserBook(
      input.googleBookId
    );

  let startedAt =
    existing?.started_at ??
    null;

  let finishedAt =
    existing?.finished_at ??
    null;

  let dnfAt =
    existing?.dnf_at ??
    null;

  if (
    input.status ===
    'reading'
  ) {
    startedAt =
      startedAt ?? now;

    finishedAt =
      null;

    dnfAt =
      null;
  }

  if (
    input.status ===
    'read'
  ) {
    // Selecting Read while adding/classifying a book describes
    // its state; it does not mean the user finished it today.
    // Actual journey completion is handled by the Reading Journey
    // lifecycle, which records the real completion date.
    finishedAt =
      existing?.status ===
        'read'
        ? existing.finished_at
        : null;

    dnfAt =
      null;
  }

  if (
    input.status ===
    'dnf'
  ) {
    // Initial DNF classification also carries no implied date.
    // A dated DNF journey is recorded through Reading Details.
    dnfAt =
      existing?.status ===
        'dnf'
        ? existing.dnf_at
        : null;

    finishedAt =
      null;
  }

  if (
    input.status ===
    'want_to_read'
  ) {
    finishedAt =
      null;

    dnfAt =
      null;
  }

  if (existing) {
    const {
      data,
      error,
    } = await supabase
      .from('user_books')
      .update({
        title:
          input.title,
        authors:
          input.authors ?? [],
        cover_url:
          input.coverUrl ?? existing.cover_url,
        isbn:
          input.isbn ??
          null,
        published_date:
          input.publishedDate ??
          null,
        status:
          input.status ??
          existing.status,
        owned:
          input.owned ??
          existing.owned ??
          false,
        started_at:
          startedAt,
        finished_at:
          finishedAt,
        dnf_at:
          dnfAt,
        updated_at:
          now,
      })
      .eq(
        'id',
        existing.id
      )
      .eq(
        'user_id',
        userId
      )
      .select('*')
      .single();

    if (error) {
      throw error;
    }

    markLibraryChanged();

    return data as UserBook;
  }

  const {
    data,
    error,
  } = await supabase
    .from('user_books')
    .insert({
      user_id:
        userId,
      google_book_id:
        input.googleBookId,
      title:
        input.title,
      authors:
        input.authors ?? [],
      cover_url:
        input.coverUrl ??
        null,
      isbn:
        input.isbn ??
        null,
      published_date:
        input.publishedDate ??
        null,
      status:
        input.status ??
        null,
      owned:
        input.owned ??
        false,
      started_at:
        startedAt,
      finished_at:
        finishedAt,
      dnf_at:
        dnfAt,
      updated_at:
        now,
    })
    .select('*')
    .single();

  if (error) {
    throw error;
  }

  markLibraryChanged();

  return data as UserBook;
}

